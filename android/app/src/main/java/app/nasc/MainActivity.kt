/**
 * Starts the Go core in-process and shows its loopback web app full screen.
 * The WebView can only ever navigate to that loopback origin; everything else
 * (links in the terminal) is handed to the system browser.
 */
class MainActivity : AppCompatActivity() {

    private lateinit var web: WebView
    private var origin: String? = null
    private var pendingFiles: ValueCallback<Array<Uri>>? = null
    private lateinit var dataDir: File
    private lateinit var root: FrameLayout
    private var cover: View? = null
    private var coreRunning = false
    private var stoppedAt = 0L

    // The system closes a biometric prompt shown before our window is in the foreground ("owner not in
    // foreground"), so prompts requested during onCreate/onStart wait here until the window has focus.
    private var pendingAuth: (() -> Unit)? = null

    private val authenticators = if (Build.VERSION.SDK_INT >= 30)
        BiometricManager.Authenticators.BIOMETRIC_STRONG or BiometricManager.Authenticators.DEVICE_CREDENTIAL
    else BiometricManager.Authenticators.BIOMETRIC_STRONG

    // Android's WebView ignores <input type="file"> unless the app opens the picker itself.
    private val pickFile =
        registerForActivityResult(ActivityResultContracts.StartActivityForResult()) { result ->
            val data = result.data
            val uris: Array<Uri>? =
                if (result.resultCode != RESULT_OK || data == null) null
                else data.clipData?.let { clip -> Array(clip.itemCount) { clip.getItemAt(it).uri } }
                    ?: data.data?.let { arrayOf(it) }
            pendingFiles?.onReceiveValue(uris)
            pendingFiles = null
        }

    @SuppressLint("SetJavaScriptEnabled")
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        root = FrameLayout(this)
        dataDir = File(filesDir, "nasc")
        web = TerminalWebView(this).apply {
            settings.javaScriptEnabled = true
            settings.domStorageEnabled = true
            settings.allowFileAccess = false
            settings.allowContentAccess = false
            settings.mediaPlaybackRequiresUserGesture = true
            setBackgroundColor(0xFF0D1117.toInt())
            if (applicationInfo.flags and ApplicationInfo.FLAG_DEBUGGABLE != 0) {
                WebView.setWebContentsDebuggingEnabled(true)
            }
            webChromeClient = object : WebChromeClient() {
                override fun onShowFileChooser(
                    view: WebView,
                    callback: ValueCallback<Array<Uri>>,
                    params: FileChooserParams
                ): Boolean {
                    pendingFiles?.onReceiveValue(null) // a previous chooser was abandoned
                    pendingFiles = callback
                    return try {
                        // Any file type: private keys (id_ed25519, *.pem) have no usable MIME type.
                        val intent = params.createIntent().apply { type = "*/*" }
                        pickFile.launch(intent)
                        true
                    } catch (e: Exception) {
                        pendingFiles = null
                        callback.onReceiveValue(null)
                        false
                    }
                }
            }
            addJavascriptInterface(LockBridge(), "NascNative")
            webViewClient = object : WebViewClient() {
                override fun shouldOverrideUrlLoading(view: WebView, request: WebResourceRequest): Boolean {
                    val url = request.url
                    if (origin != null && url.toString().startsWith(origin!!)) return false
                    runCatching { startActivity(Intent(Intent.ACTION_VIEW, url)) }
                    return true
                }
            }
        }
        root.addView(web, FrameLayout.LayoutParams(-1, -1))
        setContentView(root)

        // Keep the page clear of the status bar / gesture bar / keyboard.
        ViewCompat.setOnApplyWindowInsetsListener(root) { v, insets ->
            val bars = insets.getInsets(WindowInsetsCompat.Type.systemBars() or WindowInsetsCompat.Type.ime())
            v.setPadding(bars.left, bars.top, bars.right, bars.bottom)
            WindowInsetsCompat.CONSUMED
        }

        // Back never closes the app: the page goes back one screen if it can (sub-screen -> host list);
        // at the top we just send the app to the background so open sessions stay alive.
        onBackPressedDispatcher.addCallback(this, object : OnBackPressedCallback(true) {
            override fun handleOnBackPressed() {
                if (cover != null) {
                    moveTaskToBack(true)
                    return
                }
                web.evaluateJavascript("(window.nascBack ? window.nascBack() : false)") { handled ->
                    if (handled != "true") moveTaskToBack(true)
                }
            }
        })

        if (Build.VERSION.SDK_INT >= 33) {
            requestPermissions(arrayOf(Manifest.permission.POST_NOTIFICATIONS), 1)
        }

        val msg = TextView(this).apply { text = "Starting…"; setTextColor(0xFF8B949E.toInt()) }
        root.addView(msg, FrameLayout.LayoutParams(-2, -2, android.view.Gravity.CENTER))

        if (SecureKey.isLocked(dataDir)) {
            root.removeView(msg)
            showCover("Nasc is locked")
            pendingAuth = ::unlockAtLaunch
        } else {
            startCore(msg) { SecureKey.plainKey(dataDir) }
        }
    }

    /** Starts the Go core with a master key obtained off the UI thread, then loads the page. */
    private fun startCore(msg: TextView?, key: () -> ByteArray) {
        thread(name = "nasc-start") {
            try {
                val url = Nasc.start(dataDir.absolutePath, key())
                origin = Uri.parse(url).let { "${it.scheme}://${it.authority}/" }
                runOnUiThread {
                    msg?.let { root.removeView(it) }
                    coreRunning = true
                    SessionService.start(this)
                    web.loadUrl(url)
                }
            } catch (e: Exception) {
                runOnUiThread { msg?.text = "Failed to start: ${e.message}" }
            }
        }
    }

    // ---- app lock ---------------------------------------------------------------------------

    private fun prompt(title: String, cipher: Cipher, onOk: (Cipher) -> Unit, onFail: (String) -> Unit) {
        val info = BiometricPrompt.PromptInfo.Builder()
            .setTitle(title)
            .setAllowedAuthenticators(authenticators)
            .apply { if (Build.VERSION.SDK_INT < 30) setNegativeButtonText("Cancel") }
            .build()
        val callback = object : BiometricPrompt.AuthenticationCallback() {
            override fun onAuthenticationSucceeded(result: BiometricPrompt.AuthenticationResult) {
                val c = result.cryptoObject?.cipher
                if (c == null) onFail("Authentication gave no key") else {
                    try { onOk(c) } catch (e: Exception) { onFail(e.message ?: "unlock failed") }
                }
            }
            override fun onAuthenticationError(code: Int, message: CharSequence) = onFail(message.toString())
        }
        BiometricPrompt(this, ContextCompat.getMainExecutor(this), callback)
            .authenticate(info, BiometricPrompt.CryptoObject(cipher))
    }

    private fun showCover(message: String, retry: (() -> Unit)? = null) {
        cover?.let { root.removeView(it) }
        val box = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            gravity = android.view.Gravity.CENTER
            setBackgroundColor(0xFF0D1117.toInt())
            isClickable = true // swallow touches meant for the page underneath
            addView(TextView(context).apply { text = message; setTextColor(0xFFE6EDF3.toInt()); textSize = 18f; gravity = android.view.Gravity.CENTER })
            addView(Button(context).apply { text = "Unlock"; setOnClickListener { (retry ?: ::relock)() } })
        }
        root.addView(box, FrameLayout.LayoutParams(-1, -1))
        cover = box
    }

    private fun hideCover() {
        cover?.let { root.removeView(it) }
        cover = null
    }

    /** Cold start with the lock on: the master key cannot be recovered without authenticating. */
    private fun unlockAtLaunch() {
        try {
            prompt("Unlock Nasc", SecureKey.unlockCipher(dataDir),
                onOk = { cipher ->
                    val key = SecureKey.openLocked(dataDir, cipher)
                    hideCover()
                    startCore(null) { key }
                },
                onFail = { showCover("Locked: $it", ::unlockAtLaunch) })
        } catch (e: Exception) {
            showCover("Locked: ${e.message}", ::unlockAtLaunch)
        }
    }

    /** Core already running (sessions alive in background): just gate the screen again. */
    private fun relock() {
        try {
            prompt("Unlock Nasc", SecureKey.unlockCipher(dataDir),
                onOk = { hideCover() },
                onFail = { showCover("Locked: $it") })
        } catch (e: Exception) {
            showCover("Locked: ${e.message}")
        }
    }

    override fun onStop() {
        stoppedAt = SystemClock.elapsedRealtime()
        super.onStop()
    }

    override fun onStart() {
        super.onStart()
        val away = SystemClock.elapsedRealtime() - stoppedAt
        if (coreRunning && stoppedAt != 0L && away > RELOCK_AFTER_MS && SecureKey.isLocked(dataDir) && cover == null) {
            showCover("Nasc is locked")
            pendingAuth = ::relock
        }
    }

    override fun onWindowFocusChanged(hasFocus: Boolean) {
        super.onWindowFocusChanged(hasFocus)
        if (hasFocus) pendingAuth?.let { pendingAuth = null; it() }
    }

    /** What the web UI can ask of the native side. Only our loopback page is ever loaded in the WebView. */
    inner class LockBridge {
        @JavascriptInterface
        fun lockSupported() = BiometricManager.from(this@MainActivity).canAuthenticate(authenticators) ==
            BiometricManager.BIOMETRIC_SUCCESS

        @JavascriptInterface
        fun lockEnabled() = SecureKey.isLocked(dataDir)

        @JavascriptInterface
        fun setLock(enable: Boolean) = runOnUiThread {
            try {
                if (enable) {
                    prompt("Turn on app lock", SecureKey.lockCipher(),
                        onOk = { cipher -> SecureKey.enableLock(dataDir, cipher); notifyLock(null) },
                        onFail = { notifyLock(it) })
                } else {
                    prompt("Turn off app lock", SecureKey.unlockCipher(dataDir),
                        onOk = { cipher ->
                            SecureKey.disableLock(dataDir, SecureKey.openLocked(dataDir, cipher))
                            notifyLock(null)
                        },
                        onFail = { notifyLock(it) })
                }
            } catch (e: Exception) {
                notifyLock(e.message ?: "failed")
            }
        }
    }

    private fun notifyLock(error: String?) {
        val detail = org.json.JSONObject()
            .put("enabled", SecureKey.isLocked(dataDir))
            .put("error", error ?: org.json.JSONObject.NULL)
        web.evaluateJavascript(
            "window.dispatchEvent(new CustomEvent('nasc-lock',{detail:$detail}))", null
        )
    }

    companion object {
        private const val RELOCK_AFTER_MS = 30_000L
    }

    override fun onDestroy() {
        if (isFinishing) {
            SessionService.stop(this)
            Nasc.stop()
        }
        web.destroy()
        super.onDestroy()
    }
}

/**
 * A WebView whose keyboard sends every character immediately. Normal keyboards hold the word being
 * typed as an uncommitted "composing" region and only deliver it on space, so the shell would not
 * have the letters yet when Tab (or an arrow key) is pressed. Declaring a visible-password field with
 * no suggestions turns composition and autocorrect off, as terminal emulators like Termux do.
 */
class TerminalWebView(context: Context) : WebView(context) {
    override fun onCreateInputConnection(outAttrs: EditorInfo): InputConnection? {
        val connection = super.onCreateInputConnection(outAttrs)
        outAttrs.inputType = InputType.TYPE_CLASS_TEXT or
            InputType.TYPE_TEXT_VARIATION_VISIBLE_PASSWORD or
            InputType.TYPE_TEXT_FLAG_NO_SUGGESTIONS
        outAttrs.imeOptions = outAttrs.imeOptions or EditorInfo.IME_FLAG_NO_FULLSCREEN
        return connection
    }
}
